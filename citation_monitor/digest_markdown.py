"""Weekly digest — Markdown rendering."""
from __future__ import annotations


def _pct(x: float) -> str:
    return f"{x:.1f}%"


def _arrow(delta: float, invert: bool = False) -> str:
    eps = 0.05
    if abs(delta) < eps:
        return "→ unchanged"
    good = (delta > 0) != invert
    return f"↑ +{delta:.1f} pts" if good else f"↓ {delta:.1f} pts"


def render_md(brand, week, mode, score, d, recs, history_rows, snippets) -> str:
    L = []
    L.append(f"# Weekly AI Visibility Digest — {brand.name} ({week})")
    L.append("")
    if mode == "demo":
        L.append("> **DEMO DATA** — generated by replaying recorded fixture responses. "
                 "Structure is exactly what a live run produces; numbers are illustrative.")
        L.append("")

    # headline numbers
    L.append("## Headline numbers")
    L.append("")
    prev = d.get("prev_summary")
    prev_line = ""
    if not d["first_run"] and prev:
        prev_line = f" (prev week {_pct(prev['sov'])}, {d['sov_delta']:+.1f} pts)"
    L.append(f"- **Share of voice: {_pct(score['sov'])}**{prev_line}")
    cite_line = f"{_pct(score['citation_rate'])} ({sum(1 for p in score['prompts'] if p['brand_any'])}/{score['n_prompts']} prompts)"
    if not d["first_run"] and prev:
        cite_line += f" — prev {_pct(prev['citation_rate'])} ({d['citation_delta']:+.1f} pts)"
    L.append(f"- **Brand citation rate: {cite_line}**")
    L.append(f"- Engines monitored: {', '.join(score['engines'].keys())} — {score['n_rows']} answers analyzed")
    L.append(f"- Approx. tokens consumed this run: {score['tokens_est']:,}")
    L.append("")

    # trend
    L.append("## Score trend")
    L.append("")
    if len(history_rows) >= 2:
        L.append("| Week | Share of voice | Citation rate |")
        L.append("|---|---|---|")
        for h in history_rows:
            L.append(f"| {h['week']} | {_pct(h['sov'])} | {_pct(h['citation_rate'])} |")
    else:
        L.append("First run — the trend line starts next week.")
    L.append("")

    # per-engine
    L.append("## Per-engine breakdown")
    L.append("")
    L.append("| Engine | Model | Answers | Brand cited | SOV |")
    L.append("|---|---|---|---|---|")
    for ename, e in score["engines"].items():
        cited = round(e["citation_rate"] / 100.0 * e["n"])
        L.append(f"| {ename} | {e['model']} | {e['n']} | {cited}/{e['n']} | {_pct(e['sov'])} |")
    L.append("")

    # competitors
    L.append("## Which competitors got cited — and why")
    L.append("")
    if score["competitors"]:
        L.append("| Competitor | Answers naming it | Δ vs last week |")
        L.append("|---|---|---|")
        for name, count in score["competitors"].items():
            delta = d["competitor_deltas"].get(name, 0)
            delta_s = f"{delta:+d}" if not d["first_run"] else "—"
            L.append(f"| {name} | {count} | {delta_s} |")
        L.append("")
        L.append("**Why they get cited (verbatim snippets from this week's answers):**")
        L.append("")
        for name in list(score["competitors"].keys())[:4]:
            for prompt_text, snip in snippets.get(name, [])[:1]:
                L.append(f"- **{name}** — prompt: “{prompt_text}”")
                L.append(f"  > {snip}")
    else:
        L.append("No competitor names detected this run.")
    L.append("")

    # changes
    L.append("## What changed this week")
    L.append("")
    if d["first_run"]:
        L.append("First stored run — diffs begin on the next run.")
    else:
        if d["gained"]:
            L.append("**Citations gained:**")
            L.append("")
            for g in d["gained"]:
                comp = ", ".join(g["now"]["competitors"]) or "—"
                L.append(f"- ✅ “{g['prompt_text']}” ({g['engine']}): brand absent last week → cited this week (alongside {comp})")
            L.append("")
        if d["lost"]:
            L.append("**Citations lost (fix these first):**")
            L.append("")
            for g in d["lost"]:
                comp = ", ".join(g["now"]["competitors"]) or "—"
                L.append(f"- ❌ “{g['prompt_text']}” ({g['engine']}): cited last week → dropped this week; competitors still named: {comp}")
            L.append("")
        if not d["gained"] and not d["lost"]:
            L.append("No citation changes week-over-week.")
            L.append("")

    # recommendations — exactly 3
    L.append("## This week's 3 actions (prioritized)")
    L.append("")
    for i, r in enumerate(recs, start=1):
        L.append(f"### {i}. [{r.priority}] {r.title}")
        L.append("")
        L.append(f"**Why:** {r.why}")
        L.append("")
        L.append("**Do this:**")
        for a in r.actions:
            L.append(f"- {a}")
        if r.targets:
            L.append("")
            L.append(f"*Target prompts:* {'; '.join('“' + t + '”' for t in r.targets[:3])}")
        L.append("")

    # methodology
    L.append("---")
    L.append("")
    L.append("**Methodology.** Answers are collected weekly from official LLM APIs "
             "(free tiers of Groq/Llama and Google Gemini by default) responding to your buyer-phrase "
             "prompts; these serve as proxies for the AI answer engines buyers actually use. "
             "Mention detection uses exact + alias matching with typo tolerance. "
             "*Share of voice* = your share of named products per answer, averaged across answers. "
             "*Citation rate* = share of answers naming your brand at all. "
             "Token use per weekly run is intentionally tiny (pennies at paid rates; $0 on free tiers).")
    if mode == "demo":
        L.append("")
        L.append("*Demo disclosure: fixture responses are synthetic and recorded by the pipeline authors; "
                 "no live API calls were made for this report.*")
    L.append("")
    return "\n".join(L)
